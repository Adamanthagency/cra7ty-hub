import { NextResponse, type NextRequest } from 'next/server';
import { serviceConfigured } from '@/lib/server/supabase-server';
import { initializeTransaction, paystackSecret, toKobo } from '@/lib/server/paystack';
import {
  confirmEventRegistration,
  createEventRegistration,
  eventsRateLimit,
  loadTicket,
  revalidateEventPages,
} from '@/lib/server/events';
import { deliverEventTicket } from '@/lib/server/event-ticket';

/**
 * POST /api/events/register — start a registration (public, rate-limited).
 *
 * SECURITY (same hard rules as Tier 4's /api/checkout):
 *   * The client NEVER sends a price. The body is { eventId, name,
 *     email, phone }; create_event_registration prices from the events
 *     row and returns the server price — THAT number (in kobo) goes to
 *     /transaction/initialize.
 *   * The reference is generated by the RPC (evr_<32 hex>), never from
 *     the client.
 *   * Nothing here marks anything paid except the FREE branch, which
 *     calls the same confirm RPC the webhook uses (see below).
 *
 * FREE PATH (price = 0): no Paystack hop at all. The pending row is
 * confirmed immediately by confirm_event_registration(reference, 0,
 * 'free') — identical idempotency and the identical atomic capacity
 * check — and the ticket comes back in this response, with the ticket
 * email fired on the confirming call. If a capped free event fills
 * between the soft check and this confirm, the loser gets
 * needsReview='capacity_shortfall' and NO ticket is issued as clean —
 * same race posture as a paid event.
 *
 * Rate limit: 10/min per IP (registration spam).
 */

export const dynamic = 'force-dynamic';

const MAX_STRING = 200;

interface RegisterBody {
  eventId?: unknown;
  name?: unknown;
  email?: unknown;
  phone?: unknown;
}

function bounded(value: unknown, max = MAX_STRING): string | null {
  if (typeof value !== 'string') return null;
  const trimmed = value.trim();
  if (!trimmed || trimmed.length > max) return null;
  return trimmed;
}

/** Map create_event_registration's raised reasons to HTTP + message. */
function mapRpcError(message: string): { status: number; body: object } {
  switch (message.split(':')[0]) {
    case 'event_not_found':
      return { status: 404, body: { error: 'event_not_found', message: 'That event does not exist.' } };
    case 'event_closed':
      return { status: 409, body: { error: 'event_closed', message: 'Registration for that event has closed.' } };
    case 'event_full':
      return {
        status: 409,
        body: {
          error: 'event_full',
          message: 'That event is full — you can join the waitlist instead.',
          waitlistAvailable: true,
        },
      };
    case 'invalid_attendee':
      return { status: 400, body: { error: 'invalid_attendee', message: 'Please fill in your name, email and phone.' } };
    default:
      return { status: 500, body: { error: 'register_failed', message: 'Could not start registration — try again.' } };
  }
}

export async function POST(request: NextRequest) {
  if (!serviceConfigured()) {
    return NextResponse.json({ error: 'SUPABASE_NOT_CONFIGURED' }, { status: 503 });
  }

  if (!(await eventsRateLimit('register', request))) {
    return NextResponse.json(
      { error: 'rate_limited', message: 'Too many requests — try again shortly.' },
      { status: 429 },
    );
  }

  const body = (await request.json().catch(() => null)) as RegisterBody | null;
  const eventId = bounded(body?.eventId, 80);
  const name = bounded(body?.name, 120);
  const email = bounded(body?.email, 200);
  const phone = bounded(body?.phone, 40);
  if (!body || !eventId || !name || !email || !phone || !email.includes('@')) {
    return NextResponse.json({ error: 'invalid_request' }, { status: 400 });
  }

  /* ---- step 1: server-priced pending registration ------------------ */
  let created: Awaited<ReturnType<typeof createEventRegistration>>;
  try {
    created = await createEventRegistration(eventId, { name, email, phone });
  } catch (error) {
    const err = error as Error & { status?: number };
    if (typeof err.message === 'string' && err.status === 400) {
      const mapped = mapRpcError(err.message);
      return NextResponse.json(mapped.body, { status: mapped.status });
    }
    console.error('[events] create_event_registration failed');
    return NextResponse.json(
      { error: 'register_failed', message: 'Could not start registration — try again.' },
      { status: 500 },
    );
  }

  /* ---- free path: confirm right here, no Paystack ------------------ */
  if (created.eventFree) {
    try {
      const confirmed = await confirmEventRegistration(created.reference, 0, 'free');
      if (!confirmed.alreadyProcessed) {
        // The free path seats the attendee inside this request — the
        // pages must know before the next visitor arrives.
        revalidateEventPages();
      }
      const ticket = await loadTicket(created.reference);
      if (!confirmed.needsReview && !confirmed.alreadyProcessed) {
        // The confirming call mails the ticket — exactly-once, same as
        // the webhook/verify pair on the paid side.
        await deliverEventTicket(created.reference, email);
      }
      return NextResponse.json({
        free: true,
        paid: true,
        registrationNumber: created.registrationNumber,
        reference: created.reference,
        needsReview: confirmed.needsReview,
        reviewReason: confirmed.reviewReason,
        ...(ticket ? { ticket } : {}),
      });
    } catch (error) {
      // capacity_shortfall is NOT an exception — the RPC returns it as
      // needsReview (money/place accepted, flagged for the admin), so
      // the only raises reaching here are infrastructure ones.
      console.error('[events] free confirmation failed:', (error as Error).message);
      return NextResponse.json(
        { error: 'confirm_failed', message: 'Could not confirm your spot — try again.' },
        { status: 500 },
      );
    }
  }

  /* ---- paid path: Paystack initialize with the SERVER price --------- */
  if (!paystackSecret()) {
    return NextResponse.json(
      { error: 'PAYSTACK_NOT_CONFIGURED', message: 'PAYSTACK_SECRET_KEY is not set on this server.' },
      { status: 503 },
    );
  }

  const callbackUrl = `${request.nextUrl.origin}/workshops/success?ref=${created.reference}`;
  try {
    const { authorizationUrl } = await initializeTransaction({
      email,
      amountKobo: toKobo(created.priceNaira),
      reference: created.reference,
      callbackUrl,
    });
    return NextResponse.json({
      free: false,
      authorizationUrl,
      reference: created.reference,
      registrationNumber: created.registrationNumber,
      priceNaira: created.priceNaira,
      eventName: created.eventName,
    });
  } catch (error) {
    // The pending row stays behind — it holds NO seat (Tier 4
    // semantics), so an abandoned initialize is harmless.
    console.error(`[events] initialize failed: ${(error as Error).message}`);
    return NextResponse.json(
      { error: 'payment_init_failed', message: 'Could not reach the payment provider — try again.' },
      { status: 502 },
    );
  }
}
