import { NextResponse, type NextRequest } from 'next/server';
import {
  rateLimit,
  rpc,
  serviceConfigured,
} from '@/lib/server/supabase-server';
import {
  initializeTransaction,
  paystackSecret,
  toKobo,
} from '@/lib/server/paystack';

/**
 * POST /api/checkout — checkout initialize (public, rate-limited).
 *
 * SECURITY (approved Tier 4 plan, hard requirements):
 *   * The client NEVER sends a price. It sends product ids, variant
 *     keys, quantities, customer details and an optional coupon code.
 *     create_checkout_order (RPC) prices every line from products itself
 *     (variant priceOverride honoured) and returns the server total —
 *     THAT total (in kobo) is what goes to /transaction/initialize.
 *   * The reference is generated by the RPC (chr_<32 hex>), never from
 *     the client — no collision/replay surface.
 *   * Coupon validity and discount come from the coupon_codes row.
 *   * Nothing here marks anything paid: confirmation happens only in
 *     the webhook / verify paths via confirm_paid_order.
 *
 * Rate limit: POST /api/checkout — 10/min per IP (pending-order spam).
 */

export const dynamic = 'force-dynamic';

const RATE = { limit: 10, windowSeconds: 60 };
const MAX_LINES = 50;
const MAX_QUANTITY = 99;
const MAX_STRING = 500;

interface CheckoutLine {
  productId: string;
  variantKey?: string;
  variantLabel?: string;
  quantity: number;
}

interface CheckoutCustomer {
  name: string;
  email: string;
  phone: string;
  address: string;
}

interface CheckoutBody {
  lines?: unknown;
  customer?: unknown;
  coupon?: unknown;
}

function asBoundedString(value: unknown, max: number): string | null {
  if (typeof value !== 'string') return null;
  const trimmed = value.trim();
  if (!trimmed || trimmed.length > max) return null;
  return trimmed;
}

function parseLines(raw: unknown): CheckoutLine[] | null {
  if (!Array.isArray(raw) || raw.length === 0 || raw.length > MAX_LINES) {
    return null;
  }
  const lines: CheckoutLine[] = [];
  for (const entry of raw) {
    if (!entry || typeof entry !== 'object') return null;
    const line = entry as Record<string, unknown>;
    const productId = asBoundedString(line.productId, 200);
    const quantity = line.quantity;
    if (!productId) return null;
    if (
      typeof quantity !== 'number' ||
      !Number.isInteger(quantity) ||
      quantity < 1 ||
      quantity > MAX_QUANTITY
    ) {
      return null;
    }
    const variantKey = asBoundedString(line.variantKey, 300);
    const variantLabel = asBoundedString(line.variantLabel, 200);
    lines.push({
      productId,
      quantity,
      ...(variantKey ? { variantKey } : {}),
      ...(variantLabel ? { variantLabel } : {}),
    });
  }
  return lines;
}

function parseCustomer(raw: unknown): CheckoutCustomer | null {
  if (!raw || typeof raw !== 'object') return null;
  const customer = raw as Record<string, unknown>;
  const name = asBoundedString(customer.name, 120);
  const email = asBoundedString(customer.email, 200);
  const phone = asBoundedString(customer.phone, 40);
  const address = asBoundedString(customer.address, MAX_STRING);
  // Deliberately light: the real gate is "non-empty string"; deep email
  // syntax checking belongs to Paystack at the payment step.
  if (!name || !email || !phone || !address) return null;
  if (!email.includes('@')) return null;
  return { name, email, phone, address };
}

/** Map create_checkout_order's raised reasons to HTTP codes + messages. */
function mapRpcError(message: string): { status: number; body: object } {
  const [reason, detail] = message.split(':', 2);
  switch (reason) {
    case 'product_unavailable':
      return {
        status: 400,
        body: {
          error: 'product_unavailable',
          message: `One of the products in your order is no longer available (${detail}).`,
        },
      };
    case 'out_of_stock':
      return {
        status: 409,
        body: {
          error: 'out_of_stock',
          message: `Not enough stock left for one of the items (${detail}).`,
        },
      };
    case 'coupon_invalid':
      return {
        status: 400,
        body: { error: 'coupon_invalid', message: 'That coupon code is not valid.' },
      };
    case 'coupon_expired':
      return {
        status: 400,
        body: { error: 'coupon_expired', message: 'That coupon code has expired.' },
      };
    case 'coupon_exhausted':
      return {
        status: 400,
        body: {
          error: 'coupon_exhausted',
          message: 'That coupon code has already been fully used.',
        },
      };
    case 'coupon_min_not_met':
      return {
        status: 400,
        body: {
          error: 'coupon_min_not_met',
          minAmount: Number(detail) || 0,
          message: 'That coupon requires a higher order minimum.',
        },
      };
    case 'empty_order':
    case 'invalid_line':
    case 'missing_customer_details':
      return {
        status: 400,
        body: { error: 'invalid_request', message: 'Your order details are incomplete.' },
      };
    default:
      return {
        status: 500,
        body: { error: 'checkout_failed', message: 'Could not start checkout — try again.' },
      };
  }
}

export async function POST(request: NextRequest) {
  if (!serviceConfigured()) {
    return NextResponse.json(
      { error: 'SUPABASE_NOT_CONFIGURED' },
      { status: 503 },
    );
  }

  // Paystack secret needed to initialize (mock mode has its own seam in
  // paystack.ts; the 503 still names the real variable).
  if (!paystackSecret()) {
    return NextResponse.json(
      {
        error: 'PAYSTACK_NOT_CONFIGURED',
        message: 'PAYSTACK_SECRET_KEY is not set on this server.',
      },
      { status: 503 },
    );
  }

  if (!(await rateLimit('checkout', RATE.limit, RATE.windowSeconds, request))) {
    return NextResponse.json(
      { error: 'rate_limited', message: 'Too many requests — try again shortly.' },
      { status: 429 },
    );
  }

  const body = (await request.json().catch(() => null)) as CheckoutBody | null;
  if (!body || typeof body !== 'object') {
    return NextResponse.json({ error: 'invalid_request' }, { status: 400 });
  }

  const lines = parseLines(body.lines);
  const customer = parseCustomer(body.customer);
  if (!lines || !customer) {
    return NextResponse.json({ error: 'invalid_request' }, { status: 400 });
  }

  const coupon =
    typeof body.coupon === 'string' && body.coupon.trim()
      ? body.coupon.trim().slice(0, 40)
      : null;

  // The single source of truth for pricing: lines priced from products,
  // coupon validated against its row, pending order + items inserted.
  let created: {
    orderId: string;
    orderNumber: string;
    reference: string;
    subtotal: number;
    discount: number;
    total: number;
  };
  try {
    created = await rpc<typeof created>('create_checkout_order', {
      p_lines: lines,
      p_customer: customer,
      p_coupon: coupon,
    });
  } catch (error) {
    const err = error as Error & { status?: number };
    // PostgREST surfaces raised messages verbatim; anything else is an
    // infrastructure failure, not a client error.
    if (typeof err.message === 'string' && err.status === 400) {
      const mapped = mapRpcError(err.message);
      return NextResponse.json(mapped.body, { status: mapped.status });
    }
    console.error('[checkout] create_checkout_order failed');
    return NextResponse.json(
      { error: 'checkout_failed', message: 'Could not start checkout — try again.' },
      { status: 500 },
    );
  }

  // The browser returns here after Paystack; the page then calls
  // /api/checkout/verify (backup confirmation path — webhook is primary).
  const callbackUrl = `${request.nextUrl.origin}/checkout/success?ref=${created.reference}`;

  let authorizationUrl: string;
  try {
    ({ authorizationUrl } = await initializeTransaction({
      email: customer.email,
      // Server-computed total → kobo. Never anything from the client.
      amountKobo: toKobo(created.total),
      reference: created.reference,
      callbackUrl,
    }));
  } catch (error) {
    // Known paystack.ts error names only — no headers, no key, no body.
    console.error(
      `[checkout] initialize failed: ${(error as Error).message}`,
    );
    return NextResponse.json(
      {
        error: 'payment_init_failed',
        message: 'Could not reach the payment provider — try again.',
      },
      { status: 502 },
    );
  }

  return NextResponse.json({
    authorizationUrl,
    reference: created.reference,
    orderNumber: created.orderNumber,
    subtotal: created.subtotal,
    discount: created.discount,
    total: created.total,
  });
}
