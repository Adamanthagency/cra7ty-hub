/**
 * Paystack raw REST client — server-only. No SDK (matching the project's
 * no-dependency pattern: GoTrue in the admin is plain fetch too).
 *
 * Reads PAYSTACK_SECRET_KEY from env. The key NEVER leaves this module's
 * server-side scope: never NEXT_PUBLIC_, never in a response body, never
 * logged (error paths name the stage and status code only).
 *
 * Amounts cross this boundary in KOBO (naira × 100) — Paystack's unit.
 * Everything inside the database stays whole naira (the codebase-wide
 * convention); conversion happens only in this module.
 */

import { createHmac, timingSafeEqual } from 'node:crypto';
import { readFileSync } from 'node:fs';

const PAYSTACK_BASE = 'https://api.paystack.co';

/** A hung Paystack call must not hang a checkout. */
const PAYSTACK_TIMEOUT_MS = 10_000;

export function paystackSecret(): string | null {
  return process.env.PAYSTACK_SECRET_KEY || null;
}

export function paystackPublicKey(): string | null {
  return process.env.NEXT_PUBLIC_PAYSTACK_PUBLIC_KEY || null;
}

/* ── TEST-ONLY seam (approved plan) ───────────────────────────────
 * With PAYSTACK_MOCK=1 the two outbound calls are answered from a local
 * JSON fixture file instead of the network: automated verification
 * exercises the real DB, RPCs, amount comparison, signatures and rate
 * limits with ZERO calls to Paystack's API (the Vercel key is live-mode).
 *
 * Two hard rails:
 *   1. In a Vercel production environment the mock REFUSES to engage
 *      and every checkout call fails loudly (PAYSTACK_MOCK_IN_PRODUCTION)
 *      — a stray env var can never fake (or silently bypass) payments in
 *      production. Fail closed, never open.
 *   2. The fixture file is read server-side only; it never exists in
 *      any deployment (PAYSTACK_MOCK is never set outside local tests).
 *
 * Fixture shape: { "<reference>": { "status": "success"|"failed"|…,
 *                 "amountKobo": <int>, "paidAt"?: <iso> } }
 * Path override: PAYSTACK_MOCK_STATE_FILE (default .verify/…).
 * Default for an unknown reference: null ("not found" — same as a
 * verify call for a reference Paystack doesn't know).
 * ──────────────────────────────────────────────────────────────── */

const MOCK_STATE_FILE =
  process.env.PAYSTACK_MOCK_STATE_FILE ?? '.verify/paystack-mock-state.json';

/** Throws in production rather than silently falling through to live. */
function mockMode(): boolean {
  if (process.env.PAYSTACK_MOCK !== '1') return false;
  if (process.env.VERCEL_ENV === 'production') {
    console.error('[paystack] PAYSTACK_MOCK is set in production — refusing');
    throw new Error('PAYSTACK_MOCK_IN_PRODUCTION');
  }
  return true;
}

interface MockEntry {
  status: string;
  amountKobo: number;
  paidAt?: string;
}

function readMockEntry(reference: string): MockEntry | null {
  try {
    const map = JSON.parse(
      readFileSync(MOCK_STATE_FILE, 'utf8'),
    ) as Record<string, MockEntry>;
    const entry = map[reference];
    if (!entry || typeof entry.status !== 'string') return null;
    return {
      status: entry.status,
      amountKobo: Number(entry.amountKobo) || 0,
      paidAt: entry.paidAt ?? new Date().toISOString(),
    };
  } catch {
    // Missing or malformed fixture file = "Paystack doesn't know it".
    return null;
  }
}

/** Whole naira → kobo. The only conversion point. */
export function toKobo(naira: number): number {
  return Math.round(naira * 100);
}

export interface InitializeResult {
  authorizationUrl: string;
  reference: string;
}

export interface PaystackVerifyData {
  reference: string;
  /** string status: 'success' | 'failed' | 'abandoned' | … */
  status: string;
  /** Amount in kobo as Paystack holds it. */
  amount: number;
  paidAt: string | null;
}

interface PaystackEnvelope<T> {
  status: boolean;
  message: string;
  data?: T;
}

function headers(): Record<string, string> {
  const secret = paystackSecret();
  if (!secret) throw new Error('PAYSTACK_MISSING');
  return {
    Authorization: `Bearer ${secret}`,
    'Content-Type': 'application/json',
  };
}

/**
 * POST /transaction/initialize — starts a charge for a server-computed
 * amount. `amountKobo` must come from the DB-priced order total, never
 * from a client. The reference is the one already stored on the order
 * (generated by create_checkout_order) so the webhook/verify path can
 * always find it.
 */
export async function initializeTransaction(opts: {
  email: string;
  amountKobo: number;
  reference: string;
  callbackUrl: string;
}): Promise<InitializeResult> {
  if (mockMode()) {
    // No network: the reference is the one create_checkout_order made;
    // the fixture file decides what verify later reports for it.
    return {
      authorizationUrl: `https://checkout.paystack.com/mock/${opts.reference}`,
      reference: opts.reference,
    };
  }

  const response = await fetch(`${PAYSTACK_BASE}/transaction/initialize`, {
    method: 'POST',
    headers: headers(),
    body: JSON.stringify({
      email: opts.email,
      amount: opts.amountKobo,
      reference: opts.reference,
      callback_url: opts.callbackUrl,
      // naira; Paystack's dashboard currency decides display
      currency: 'NGN',
    }),
    signal: AbortSignal.timeout(PAYSTACK_TIMEOUT_MS),
  });

  const body = (await response.json().catch(() => ({}))) as PaystackEnvelope<{
    authorization_url: string;
    reference: string;
  }>;

  if (!response.ok || !body.status || !body.data?.authorization_url) {
    // Log the stage and status only — never headers, never the key.
    console.error(
      `[paystack] initialize failed: HTTP ${response.status} ${body.message ?? ''}`.trim(),
    );
    throw new Error('PAYSTACK_INIT_FAILED');
  }

  return {
    authorizationUrl: body.data.authorization_url,
    reference: body.data.reference || opts.reference,
  };
}

/**
 * GET /transaction/verify/:reference — the authoritative check against
 * Paystack's own record. Both the webhook handler and verify-on-redirect
 * call this before trusting any payload: the amount returned here is what
 * confirm_paid_order compares against the server total.
 */
export async function verifyTransaction(
  reference: string,
): Promise<PaystackVerifyData | null> {
  if (mockMode()) {
    const entry = readMockEntry(reference);
    if (!entry) return null;
    return {
      reference,
      status: entry.status,
      amount: entry.amountKobo,
      paidAt: entry.paidAt ?? null,
    };
  }

  let response: Response;
  try {
    response = await fetch(
      `${PAYSTACK_BASE}/transaction/verify/${encodeURIComponent(reference)}`,
      {
        headers: headers(),
        signal: AbortSignal.timeout(PAYSTACK_TIMEOUT_MS),
      },
    );
  } catch {
    // Network failure reaching Paystack — the caller decides retry vs.
    // surface. Never logged with detail beyond the fact of it.
    console.error('[paystack] verify unreachable');
    return null;
  }

  const body = (await response.json().catch(() => ({}))) as PaystackEnvelope<{
    reference: string;
    status: string;
    amount: number;
    paid_at: string | null;
  }>;

  if (!response.ok || !body.status || !body.data) {
    console.error(`[paystack] verify failed: HTTP ${response.status}`.trim());
    return null;
  }

  return {
    reference: body.data.reference,
    status: body.data.status,
    amount: body.data.amount,
    paidAt: body.data.paid_at ?? null,
  };
}

/**
 * HMAC-SHA512 of the RAW request body with the secret key, compared
 * against x-paystack-signature with a timing-safe equality. The raw
 * body matters: re-serializing parsed JSON would change byte order and
 * break every signature.
 */
export function isValidWebhookSignature(
  rawBody: string,
  signatureHeader: string | null,
): boolean {
  const secret = paystackSecret();
  if (!secret || !signatureHeader) return false;

  const expected = createHmac('sha512', secret).update(rawBody).digest('hex');
  const a = Buffer.from(expected, 'utf8');
  const b = Buffer.from(signatureHeader, 'utf8');
  if (a.length !== b.length) return false;
  return timingSafeEqual(a, b);
}
